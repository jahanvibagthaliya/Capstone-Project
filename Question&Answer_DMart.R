# Question 5: Revenue generated by different Marketing and Advertisement

library(tidyverse)
revenue_by_marketing <- df %>%
  mutate(
    Total_Revenue = as.numeric(trimws(Total.Order.Value))
  ) %>%
  filter(
    Order.Status %in% c("Shipping","Delivered"),
    !is.na(Total_Revenue)
  ) %>%
  group_by(
    Marketing.Advertisement
  ) %>%
  summarise(
    Total_Revenue = sum(Total_Revenue)
  ) %>%
  arrange(desc(Total_Revenue))

print("Revenue Generated by Marketing/Advertisement Channel:")
print(revenue_by_marketing)






# Question 6: Visual representation of Total revenue generated by Marketing / Advertisement using Pie Chart

